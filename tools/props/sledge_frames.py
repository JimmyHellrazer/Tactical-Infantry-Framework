def euler_deg(R):
    # Source angles (pitch, yaw, roll) of a rotation matrix whose columns are forward (x), left (y), up (z)
    f, l, u = R[:, 0], R[:, 1], R[:, 2]
    pitch = -np.degrees(np.arcsin(np.clip(f[2], -1, 1)))
    yaw = np.degrees(np.arctan2(f[1], f[0]))
    roll = np.degrees(np.arctan2(l[2], u[2]))
    return np.array([pitch, yaw, roll])


